import { chmodSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createInterface } from 'node:readline';
import { stdin, stdout } from 'node:process';
import { paths, loadConfig } from './config.js';
import { sendTestEmail, describeMailConfig } from './mailer.js';
import { installSchedule, parseScheduleTime, scheduleStatus } from './schedule.js';

const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

const MANAGED_KEYS = new Set([
  'DIGEST_TO',
  'MAIL_FROM',
  'SMTP_HOST',
  'SMTP_PORT',
  'SMTP_SECURE',
  'SMTP_USER',
  'SMTP_PASS',
  'RESEND_API_KEY',
  'SCHEDULE_TIME',
  'SEND_EMPTY',
  'MAX_AGE_DAYS',
  'ENRICH_LIMIT',
  'USE_LLM',
  'OPENCODE_MODEL',
  'OPENCODE_BIN',
  'LLM_LIMIT',
  'LLM_TIMEOUT_MS',
]);

function parseEnvFile(text) {
  const map = new Map();
  for (const line of text.split('\n')) {
    const match = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
    if (match) map.set(match[1], match[2]);
  }
  return map;
}

function envValue(value) {
  const text = String(value ?? '');
  if (/^[A-Za-z0-9@._/:+-]*$/.test(text)) return text;
  return `"${text.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

function buildEnvFile(values) {
  const known = [];
  for (const [key, value] of Object.entries(values)) {
    known.push(`${key}=${envValue(value)}`);
  }

  let preserved = [];
  if (existsSync(paths.env)) {
    const existing = parseEnvFile(readFileSync(paths.env, 'utf8'));
    for (const [key, value] of existing) {
      if (!MANAGED_KEYS.has(key)) preserved.push(`${key}=${value}`);
    }
  }

  return [
    '# Generated by `npm run setup`. This file is gitignored — keep it private.',
    ...known,
    ...(preserved.length ? ['', ...preserved] : []),
    '',
  ].join('\n');
}

export function askHidden(rl, query) {
  return new Promise((resolve) => {
    // Node normally exposes _writeToOutput on readline.Interface, but some
    // terminal/Node combinations do not. Suppress echo rather than crashing.
    const original =
      typeof rl._writeToOutput === 'function' ? rl._writeToOutput.bind(rl) : null;
    if (!original) rl._writeToOutput = () => {};

    stdout.write(query);
    rl._writeToOutput = (text) => {
      if (original) original(String(text).replace(/[^\r\n]/g, '*'));
    };

    rl.question('', (answer) => {
      if (original) rl._writeToOutput = original;
      else delete rl._writeToOutput;
      stdout.write('\n');
      resolve(answer.trim());
    });
  });
}

function askRaw(rl, prompt) {
  return new Promise((resolve) => rl.question(prompt, resolve));
}

export async function ask(rl, question, fallback = '') {
  const suffix = fallback ? ` [${fallback}]` : '';
  const answer = (await askRaw(rl, `${question}${suffix}: `)).trim();
  return answer || fallback;
}

async function confirm(rl, question, fallback = true) {
  const answer = (await askRaw(rl, `${question} [${fallback ? 'Y/n' : 'y/N'}]: `)).trim();
  if (!answer) return fallback;
  return /^y/i.test(answer);
}

async function askEmail(rl, question, fallback) {
  for (let attempt = 0; attempt < 3; attempt += 1) {
    const value = await ask(rl, question, fallback);
    if (EMAIL_RE.test(value)) return value;
    stdout.write('That does not look like an email address. Try again.\n');
  }
  throw new Error('No valid email address provided.');
}

export async function runSetup() {
  const config = loadConfig();
  const rl = createInterface({ input: stdin, output: stdout });

  try {
    stdout.write('\nScholarship Watcher — setup\n');
    stdout.write('Fully funded only. No application fees. One email per day.\n\n');

    const to = await askEmail(rl, 'Send the daily digest to', config.mail.to);

    let provider = '';
    if (config.mail.resendKey) provider = '3';
    else if (config.mail.smtpHost) provider = config.mail.smtpHost === 'smtp.gmail.com' ? '1' : '2';

    if (!provider) {
      stdout.write('\nHow should the digest be delivered?\n');
      stdout.write('  1) Gmail SMTP (app password)\n');
      stdout.write('  2) Other SMTP server\n');
      stdout.write('  3) Resend API\n');
      stdout.write('  4) No email — just write the digest to data/digests/\n');
      provider = await ask(rl, 'Choose 1-4', '1');
      while (!['1', '2', '3', '4'].includes(provider)) {
        stdout.write('Pick 1, 2, 3 or 4.\n');
        provider = await ask(rl, 'Choose 1-4', '1');
      }
    }

    const mail = {
      to,
      from: config.mail.from,
      smtpHost: '',
      smtpPort: 465,
      smtpSecure: true,
      smtpUser: '',
      smtpPass: '',
      resendKey: '',
    };

    if (provider === '1') {
      stdout.write('\nGmail needs an App Password, not your normal password:\n');
      stdout.write('https://myaccount.google.com/apppasswords (2-Step Verification must be on)\n');
      mail.smtpHost = 'smtp.gmail.com';
      mail.smtpPort = 465;
      mail.smtpSecure = true;
      mail.smtpUser = await ask(rl, 'Gmail address', config.mail.smtpUser || to);
      mail.from = await ask(rl, 'From address', config.mail.from || mail.smtpUser);
      mail.smtpPass = (await askHidden(rl, 'Gmail app password (input hidden): ')).replace(/\s+/g, '');
    } else if (provider === '2') {
      mail.smtpHost = await ask(rl, 'SMTP host', config.mail.smtpHost);
      mail.smtpPort = Number(await ask(rl, 'SMTP port', String(config.mail.smtpPort || 587)));
      mail.smtpSecure = await confirm(rl, 'Use implicit TLS (port 465)?', mail.smtpPort === 465);
      mail.smtpUser = await ask(rl, 'SMTP username', config.mail.smtpUser);
      mail.smtpPass = await askHidden(rl, 'SMTP password (input hidden): ');
      mail.from = await ask(rl, 'From address', config.mail.from || mail.smtpUser);
    } else if (provider === '3') {
      stdout.write('\nResend: create a key at https://resend.com/api-keys\n');
      mail.resendKey = askHidden('Resend API key (input hidden): ');
      mail.from = await ask(
        rl,
        'From address (must be a verified domain, or onboarding@resend.dev)',
        config.mail.from || 'Scholarship Watcher <onboarding@resend.dev>',
      );
    } else {
      stdout.write('\nLocal mode: the digest will be written to data/digests/ and printed to the terminal.\n');
    }

    const time = await ask(rl, 'Daily run time (24-hour HH:MM)', process.env.SCHEDULE_TIME || '08:00');
    parseScheduleTime(time);

    const useLlm = await confirm(
      rl,
      'Enable optional opencode AI verification? (slower, uses your model credits)',
      config.useLlm,
    );
    let model = config.llmModel;
    if (useLlm) {
      model = await ask(
        rl,
        'opencode model (blank = your CLI default, e.g. provider/model)',
        model,
      );
      stdout.write('AI review is enabled. If the model is not reachable, the watcher falls back to keyword rules.\n');
    }

    const values = {
      DIGEST_TO: to,
      MAIL_FROM: mail.from,
      SMTP_HOST: mail.smtpHost,
      SMTP_PORT: String(mail.smtpPort),
      SMTP_SECURE: String(mail.smtpSecure),
      SMTP_USER: mail.smtpUser,
      SMTP_PASS: mail.smtpPass,
      RESEND_API_KEY: mail.resendKey,
      SCHEDULE_TIME: time,
      SEND_EMPTY: 'true',
      SAVE_WITHOUT_EMAIL: String(provider === '4'),
      MAX_AGE_DAYS: '60',
      ENRICH_LIMIT: '30',
      USE_LLM: String(useLlm),
      OPENCODE_MODEL: model,
      OPENCODE_BIN: 'opencode',
      LLM_LIMIT: '24',
      LLM_TIMEOUT_MS: '240000',
    };

    writeFileSync(paths.env, buildEnvFile(values), { mode: 0o600 });
    chmodSync(paths.env, 0o600);
    stdout.write(`\nSaved ${paths.env} (mode 600).\n`);

    const shouldSchedule = await confirm(rl, 'Install the daily schedule now?', true);
    if (shouldSchedule) {
      const result = installSchedule({ time });
      stdout.write(
        result.loaded
          ? `Schedule installed for ${result.time} daily (${result.file}).\n`
          : `Schedule file written to ${result.file}, but launchctl did not confirm it. Check: launchctl print gui/$(id -u)/${'com.scholarshipwatcher.daily'}\n`,
      );
    } else {
      stdout.write('Skipped scheduling. You can run `npm run schedule -- --time 08:00` later.\n');
    }

    const mailStatus = describeMailConfig(mail);
    if (mailStatus.configured) {
      const shouldTest = await confirm(rl, 'Send a test email now?', true);
      if (shouldTest) {
        const result = await sendTestEmail(mail);
        stdout.write(
          result.sent
            ? `Test email sent to ${to} via ${result.transport}.\n`
            : `Test email failed: ${result.reason}\n`,
        );
      }
    } else {
      stdout.write(`No email configured (${mailStatus.reason}). The digest will be written locally.\n`);
    }

    const status = scheduleStatus();
    stdout.write('\nDone.\n');
    stdout.write(`  Preview now: npm run preview\n`);
    stdout.write(`  Real run:    npm run run\n`);
    stdout.write(`  Instagram:   npm run instagram:login (once, optional)\n`);
    stdout.write(`  Schedule:    ${status.installed ? 'installed' : 'not installed'}\n`);
    stdout.write(`  Digests:     ${paths.digests}\n`);
  } finally {
    rl.close();
  }
}
